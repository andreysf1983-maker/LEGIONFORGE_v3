import type { ShopCategoryKey, ShopDeliveryKey, ShopItemInput } from "./shop";

// Default catalog inserted once on first start. After that the list is fully
// managed from the panel (edits and deletions are never overwritten).
// Prices assume the default online reward of 50 essences per hour
// (see the "Economy" note in docs/BUILD_GUIDE_RU.md). At that rate a single
// day of active play grants ~1200 essences, so the top tier stays aspirational.

function entry(
  category: ShopCategoryKey,
  sortOrder: number,
  name: string,
  itemId: number | null,
  price: number,
  description: string,
  extra: Partial<Pick<ShopItemInput, "quantity" | "classId" | "enabled">> & { delivery?: ShopDeliveryKey } = {},
): ShopItemInput {
  return { category, name, description, price, itemId, quantity: 1, delivery: "item", classId: 0, enabled: true, sortOrder, ...extra };
}

const service = (sortOrder: number, name: string, delivery: ShopDeliveryKey, price: number, description: string, enabled = true) =>
  entry("services", sortOrder, name, null, price, description, { delivery, enabled });

// Legacy tomes: itemId is null until the custom tome item exists in the world DB
// (created by custom/sql/custom_database.sql). The C++ learn script maps each
// tome item to the real removed SpellID and enforces the class check.
const tome = (sortOrder: number, name: string, classId: number, description: string) =>
  entry("legacy", sortOrder, name, null, 5000, description, { classId });

